/* One-shot generator for plugins/obs-nvenc/nvenc-cs-scale.h.
 *
 * Compiles the exact NV_CS_SCALE_SRC from nvenc-d3d11.c (cs_5_0, entry cs_scale)
 * with d3dcompiler_47.dll and emits the bytecode as a C array so the plugin can
 * skip runtime D3DCompile entirely.
 *
 * Build: cl /nologo /O2 gen_cs.cpp d3dcompiler.lib /Fe:gen_cs.exe (run from the repository root;
 * the output path plugins/obs-nvenc/nvenc-cs-scale.h is relative to it)
 */
#include <windows.h>
#include <stdio.h>
#include <d3dcompiler.h>

/* MUST stay in sync with NV_CS_SCALE_SRC in plugins/obs-nvenc/nvenc-d3d11.c */
static const char SRC[] =
    "RWTexture2D<float>  src_y  : register(u0);\n"
    "RWTexture2D<float2> src_uv : register(u1);\n"
    "RWTexture2D<float>  dst_y  : register(u2);\n"
    "RWTexture2D<float2> dst_uv : register(u3);\n"
    "cbuffer cb : register(b0) { float4 src_size; float4 dst_size; };\n"
    "\n"
    "float bil1(RWTexture2D<float> t, float2 st)\n"
    "{\n"
    "    float2 i0 = floor(st);\n"
    "    float2 f  = st - i0;\n"
    "    int p0x = (int)clamp(i0.x, 0.0, src_size.x - 1.0);\n"
    "    int p0y = (int)clamp(i0.y, 0.0, src_size.y - 1.0);\n"
    "    int p1x = (int)clamp(i0.x + 1.0, 0.0, src_size.x - 1.0);\n"
    "    int p1y = (int)clamp(i0.y + 1.0, 0.0, src_size.y - 1.0);\n"
    "    float v00 = t.Load(int2(p0x, p0y));\n"
    "    float v10 = t.Load(int2(p1x, p0y));\n"
    "    float v01 = t.Load(int2(p0x, p1y));\n"
    "    float v11 = t.Load(int2(p1x, p1y));\n"
    "    return lerp(lerp(v00, v10, f.x), lerp(v01, v11, f.x), f.y);\n"
    "}\n"
    "\n"
    "float2 bil2(RWTexture2D<float2> t, float2 st)\n"
    "{\n"
    "    float2 i0 = floor(st);\n"
    "    float2 f  = st - i0;\n"
    "    int p0x = (int)clamp(i0.x, 0.0, src_size.z - 1.0);\n"
    "    int p0y = (int)clamp(i0.y, 0.0, src_size.w - 1.0);\n"
    "    int p1x = (int)clamp(i0.x + 1.0, 0.0, src_size.z - 1.0);\n"
    "    int p1y = (int)clamp(i0.y + 1.0, 0.0, src_size.w - 1.0);\n"
    "    float2 v00 = t.Load(int2(p0x, p0y));\n"
    "    float2 v10 = t.Load(int2(p1x, p0y));\n"
    "    float2 v01 = t.Load(int2(p0x, p1y));\n"
    "    float2 v11 = t.Load(int2(p1x, p1y));\n"
    "    return lerp(lerp(v00, v10, f.x), lerp(v01, v11, f.x), f.y);\n"
    "}\n"
    "\n"
    "[numthreads(8, 8, 1)]\n"
    "void cs_scale(uint3 tid : SV_DispatchThreadID)\n"
    "{\n"
    "    if (tid.x >= (uint)dst_size.x || tid.y >= (uint)dst_size.y) return;\n"
    "    float2 st = ((float2(tid.xy) + 0.5) / dst_size.xy) * src_size.xy - 0.5;\n"
    "    dst_y[tid.xy] = bil1(src_y, st);\n"
    "    if ((tid.x & 1) == 0 && (tid.y & 1) == 0) {\n"
    "        float2 stc = ((float2(tid.xy) * 0.5 + 0.5) / dst_size.zw) * src_size.zw - 0.5;\n"
    "        dst_uv[tid.xy >> 1] = bil2(src_uv, stc);\n"
    "    }\n"
    "}";

int main(void)
{
	ID3DBlob *code = NULL, *err = NULL;
	HRESULT hr = D3DCompile(SRC, sizeof(SRC) - 1, "nvenc_staged_resize", NULL, NULL, "cs_scale", "cs_5_0", 0, 0, &code,
	                        &err);
	if (FAILED(hr)) {
		fprintf(stderr, "compile failed hr=0x%08lX\n", (unsigned long)hr);
		if (err)
			fputs((const char *)err->GetBufferPointer(), stderr);
		return 1;
	}

	UINT size = code->GetBufferSize();
	const BYTE *p = (const BYTE *)code->GetBufferPointer();
	FILE *f = fopen("plugins/obs-nvenc/nvenc-cs-scale.h", "w");
	if (!f) {
		fprintf(stderr, "cannot open plugins/obs-nvenc/nvenc-cs-scale.h for writing\n");
		return 1;
	}

	fprintf(f,
	        "/* AUTO-GENERATED by plugins/obs-nvenc/gen_cs.cpp - do not edit by hand.\n"
	        " * cs_5_0 bytecode for NV_CS_SCALE_SRC (plugins/obs-nvenc/nvenc-d3d11.c),\n"
	        " * compiled with d3dcompiler_47.dll. Regenerate: cl /nologo /O2 gen_cs.cpp\n"
	        " * d3dcompiler.lib && gen_cs.exe (run from the repository root). */\n"
	        "#pragma once\n\n");
	fprintf(f, "static const unsigned char NV_CS_SCALE_CODE[%u] = {\n", size);
	for (UINT i = 0; i < size; i++) {
		fprintf(f, "0x%02X,", p[i]);
		fprintf(f, (i % 12) == 11 ? "\n" : " ");
	}
	fprintf(f, "};\n\nstatic const unsigned int NV_CS_SCALE_CODE_SIZE = %u;\n", size);
	fclose(f);

	printf("wrote plugins/obs-nvenc/nvenc-cs-scale.h (%u bytes of bytecode)\n", size);
	if (err)
		err->Release();
	code->Release();
	return 0;
}
